"""Write the Android app's launcher icon from the generated Episteme SVG (0061).

`web/static/logo/episteme.svg` is itself generated (graphics/logo/build_svg.py),
so the icon is a translation of it and not a second drawing of the mark, the same
call `build_pwa_icons.py` makes. A translation and not a rasterization: an adaptive
icon's foreground is a VectorDrawable, and every path in the SVG maps onto one, so
the icon is sharp at every launcher size from one file.

The translation covers exactly what build_svg.py emits today: `<path>` elements
with M, L and Z commands, solid colours and opacities. Anything else (a gradient,
a curve, a new attribute) stops the script rather than being dropped, because a
dropped attribute renders as a wrong icon that nothing complains about.

The size of the mark is computed, not chosen. An adaptive icon is 108dp; the
launcher's mask shows the middle 72dp and guarantees only a 66dp circle. The
octahedron (the filled paths) is scaled to touch that circle, and the field lines,
which run to the edge of the SVG's box like a field the frame cuts off, run out
under the mask in the same way.

    uv run tools/build_android_icon.py            # write it
    uv run tools/build_android_icon.py --list     # say what it would write
"""

from __future__ import annotations

import argparse
import math
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "episteme" / "web" / "static" / "logo" / "episteme.svg"
OUT = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable" / "ic_launcher_foreground.xml"

NS = "{http://www.w3.org/2000/svg}"
CANVAS_DP = 108
SAFE_DIAMETER_DP = 66
VISIBLE_DP = 72

PATH_ATTRS = {"d", "fill", "stroke", "stroke-width", "stroke-opacity", "stroke-linecap", "stroke-linejoin"}
IGNORED_ELEMENTS = {"title", "desc"}


def color(value: str, opacity: float = 1.0) -> str | None:
    """`rgb(...)`/`rgba(...)` as `#AARRGGBB`, None for `none`."""
    if value == "none":
        return None
    m = re.fullmatch(r"rgba?\(([^)]*)\)", value)
    if not m:
        raise SystemExit(f"unsupported colour {value!r}")
    parts = [p.strip() for p in m.group(1).split(",")]
    r, g, b = (int(p) for p in parts[:3])
    alpha = (float(parts[3]) if len(parts) == 4 else 1.0) * opacity
    return f"#{round(alpha * 255):02X}{r:02X}{g:02X}{b:02X}"


def points(d: str) -> list[tuple[float, float]]:
    tokens = re.findall(r"[A-Za-z]|-?\d*\.?\d+(?:e-?\d+)?", d)
    out: list[tuple[float, float]] = []
    i = 0
    while i < len(tokens):
        cmd = tokens[i]
        if cmd == "Z":
            i += 1
        elif cmd in ("M", "L"):
            out.append((float(tokens[i + 1]), float(tokens[i + 2])))
            i += 3
        else:
            raise SystemExit(f"unsupported path command {cmd!r} in {d[:60]!r}")
    return out


def build(svg_text: str) -> tuple[str, float, float]:
    """The VectorDrawable, the box's share of the canvas, and how far the
    shortest field line reaches left and right of the centre, in dp."""
    root = ET.fromstring(svg_text)
    box = float(root.get("viewBox", "").split()[2])
    cx = cy = box / 2
    paths = []
    for el in root:
        tag = el.tag.removeprefix(NS)
        if tag in IGNORED_ELEMENTS:
            continue
        if tag != "path":
            raise SystemExit(f"unsupported element <{tag}>")
        unknown = set(el.attrib) - PATH_ATTRS
        if unknown:
            raise SystemExit(f"unsupported attributes {sorted(unknown)}")
        paths.append(el)

    octahedron = max(
        math.dist((x, y), (cx, cy)) + float(p.get("stroke-width", "0")) / 2
        for p in paths
        if p.get("fill", "none") != "none"
        for x, y in points(p.get("d", ""))
    )
    # The octahedron touches the safe circle; everything scales with it.
    scale = (SAFE_DIAMETER_DP / 2) / octahedron  # dp per SVG unit
    viewport = CANVAS_DP / scale
    pad = (viewport - box) / 2

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by tools/build_android_icon.py from",
        "     src/episteme/web/static/logo/episteme.svg. Edit the generator, never this file. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{CANVAS_DP}dp"',
        f'    android:height="{CANVAS_DP}dp"',
        f'    android:viewportWidth="{viewport:.2f}"',
        f'    android:viewportHeight="{viewport:.2f}">',
        f'    <group android:translateX="{pad:.2f}" android:translateY="{pad:.2f}">',
    ]
    for p in paths:
        points(p.get("d", ""))  # refuses what pathData would draw differently
        attrs = [f'android:pathData="{p.get("d")}"']
        fill = color(p.get("fill", "none"))
        if fill:
            attrs.append(f'android:fillColor="{fill}"')
        stroke = color(p.get("stroke", "none"), float(p.get("stroke-opacity", "1")))
        if stroke:
            attrs.append(f'android:strokeColor="{stroke}"')
            attrs.append(f'android:strokeWidth="{p.get("stroke-width", "1")}"')
            if cap := p.get("stroke-linecap"):
                attrs.append(f'android:strokeLineCap="{cap}"')
            if join := p.get("stroke-linejoin"):
                attrs.append(f'android:strokeLineJoin="{join}"')
        lines.append("        <path " + "\n            ".join(attrs) + " />")
    lines += ["    </group>", "</vector>", ""]
    # The shortest line's horizontal half-length: every line should cross the
    # square mask, whose edge is the nearest any mask comes left and right.
    field = min(
        max(abs(x - cx) for x, _ in points(p.get("d", "")))
        for p in paths
        if p.get("fill", "none") == "none"
    )
    return "\n".join(lines), box / viewport, field * scale


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--list", action="store_true", help="print the output and write nothing")
    args = ap.parse_args()

    xml, share, field_dp = build(SOURCE.read_text(encoding="utf-8"))
    note = f"mark box at {share:.0%} of {CANVAS_DP}dp, field lines reach {field_dp:.1f}dp left and right"
    if field_dp < VISIBLE_DP / 2:
        note += f" (short of the {VISIBLE_DP / 2:.0f}dp mask edge: their ends will show)"
    if args.list:
        print(f"{OUT}: {note}")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(xml, encoding="utf-8")
    print(f"wrote {OUT}: {note}")


if __name__ == "__main__":
    main()
